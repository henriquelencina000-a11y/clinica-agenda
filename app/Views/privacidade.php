<h2 class="h5 mt-4">Quais dados coletamos</h2>
<p>Nome, e-mail, telefone (opcional), senha (guardada apenas como hash) e os agendamentos que você faz. Não armazenamos prontuários nem diagnósticos.</p>
<h2 class="h5">Para que usamos</h2>
<p>Exclusivamente para identificar você, organizar suas consultas e comunicar alterações de agenda.</p>
<h2 class="h5">Quem acessa</h2>
<p>Você vê apenas os seus agendamentos. A administração da clínica acessa os dados necessários à gestão da agenda; esses acessos ficam registrados.</p>
<h2 class="h5">Por quanto tempo</h2>
<p>Pelo período necessário às finalidades acima e às obrigações legais aplicáveis. Depois disso, os dados são eliminados ou anonimizados quando permitido.</p>
<h2 class="h5">Seus direitos</h2>
<p>Você pode pedir confirmação, acesso, correção ou eliminação dos seus dados, nos termos da Lei nº 13.709/2018 (LGPD), pelo contato da clínica.</p>
